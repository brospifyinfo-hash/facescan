// Percentile of the overall score.
//
// WHAT THIS IS: the share of a MODELLED population that scores lower. The
// model draws each facial dimension around its published anthropometric
// mean (Farkas) with a realistic coefficient of variation and runs the real
// scoring pipeline over 60 000 such faces. See scripts/build-percentiles.mts.
//
// WHAT THIS IS NOT: an attractiveness ranking, and not a percentile against
// real users. The score measures conformity to published reference
// proportions — it has never been validated against attractiveness ratings.
//
// TO SWITCH TO REAL DATA: collect the overall scores of real scans, sort
// them, and replace PERCENTILE_TABLE with the empirical CDF at the same
// 0.1-step resolution. Nothing else changes.

// generated by scripts/build-percentiles.mts — n=60000, median 6.5
